create table if not exists public.comentarios (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(btrim(nome)) between 2 and 60),
  mensagem text not null check (char_length(btrim(mensagem)) between 3 and 600),
  criado_em timestamptz not null default now(),
  status text not null default 'pendente' check (status in ('pendente','aprovado','rejeitado')),
  parent_id bigint references public.comentarios(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null
);

-- Compatibilidade com eventual tabela já iniciada na versão anterior.
alter table public.comentarios add column if not exists status text not null default 'pendente';
alter table public.comentarios add column if not exists parent_id bigint references public.comentarios(id) on delete cascade;
create index if not exists comentarios_publicos_ordenados on public.comentarios(criado_em desc) where status = 'aprovado';
create index if not exists comentarios_pendentes_ordenados on public.comentarios(criado_em asc) where status = 'pendente';
create index if not exists comentarios_respostas on public.comentarios(parent_id);

-- Atribuição de permissões feita SOMENTE por administrador do banco.
create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  adicionado_em timestamptz not null default now()
);
alter table public.site_admins enable row level security;
revoke all on public.site_admins from anon,authenticated;

create or replace function public.is_site_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select (select auth.uid()) is not null and exists (
    select 1 from public.site_admins a where a.user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to anon,authenticated;

-- Permite respostas apenas a comentários principais JÁ APROVADOS.
create or replace function public.is_valid_reply_parent(p_id bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.comentarios c
    where c.id = p_id and c.status = 'aprovado' and c.parent_id is null
  );
$$;
revoke all on function public.is_valid_reply_parent(bigint) from public;
grant execute on function public.is_valid_reply_parent(bigint) to anon,authenticated;

alter table public.comentarios enable row level security;
drop policy if exists "Qualquer pessoa le comentarios aprovados" on public.comentarios;
drop policy if exists "Qualquer pessoa envia para moderacao" on public.comentarios;
drop policy if exists "Leitura publica so conteudo aprovado" on public.comentarios;
create policy "Leitura publica so conteudo aprovado"
  on public.comentarios for select to anon,authenticated
  using (status = 'aprovado' or (select public.is_site_admin()));

drop policy if exists "Inserir sempre pendente" on public.comentarios;
create policy "Inserir sempre pendente"
  on public.comentarios for insert to anon,authenticated
  with check (
    status = 'pendente'
    and (parent_id is null or (select public.is_valid_reply_parent(parent_id)))
    and (
      (auth.uid() is null and user_id is null)
      or user_id = (select auth.uid())
    )
  );

drop policy if exists "Somente admin modera" on public.comentarios;
create policy "Somente admin modera"
  on public.comentarios for update to authenticated
  using ((select public.is_site_admin()))
  with check ((select public.is_site_admin()));

drop policy if exists "Somente admin remove" on public.comentarios;
create policy "Somente admin remove"
  on public.comentarios for delete to authenticated
  using ((select public.is_site_admin()));

-- Garantia adicional: o visitante não pode passar status='aprovado' na criação.
-- RLS valida com WITH CHECK, inclusive para usuários autenticados.
-- SELECT de visitantes expõe somente os campos necessários à visualização pública.
revoke all on public.comentarios from anon,authenticated;
grant select (id,nome,mensagem,criado_em,parent_id,status) on public.comentarios to anon,authenticated;
grant insert (nome,mensagem,criado_em,status,parent_id,user_id) on public.comentarios to anon,authenticated;
grant update (nome,mensagem,status) on public.comentarios to authenticated;
grant delete on public.comentarios to authenticated;
grant usage on sequence public.comentarios_id_seq to anon,authenticated;

