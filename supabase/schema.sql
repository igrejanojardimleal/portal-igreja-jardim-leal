create table if not exists public.cifra_envios (
  id bigint generated by default as identity primary key,
  hino_numero int not null check (hino_numero between 1 and 9999),
  nome text not null check (char_length(btrim(nome)) between 2 and 60),
  tom text check (tom is null or char_length(tom) <= 20),
  observacoes text check (observacoes is null or char_length(observacoes) <= 400),
  storage_path text not null unique check (storage_path ~ '^[0-9a-fA-F-]{36}/[0-9a-fA-F-]{36}\.pdf$'),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  status text not null default 'pendente' check (status in ('pendente','aprovado','rejeitado')),
  criado_em timestamptz not null default now()
);
create index if not exists cifra_envios_pendentes on public.cifra_envios(criado_em) where status='pendente';
alter table public.cifra_envios enable row level security;
drop policy if exists "Proprio envio ou admin pode ler cifra" on public.cifra_envios;
create policy "Proprio envio ou admin pode ler cifra"
  on public.cifra_envios for select to authenticated
  using ((select auth.uid())=user_id or (select public.is_site_admin()));
drop policy if exists "Colaborador envia cifra pendente" on public.cifra_envios;
create policy "Colaborador envia cifra pendente"
  on public.cifra_envios for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and status='pendente'
    and split_part(storage_path,'/',1)=(select auth.uid())::text
  );
drop policy if exists "Somente admin altera cifra" on public.cifra_envios;
create policy "Somente admin altera cifra"
  on public.cifra_envios for update to authenticated
  using ((select public.is_site_admin()))
  with check ((select public.is_site_admin()));
revoke all on public.cifra_envios from anon,authenticated;
grant select on public.cifra_envios to authenticated;
grant insert (hino_numero,nome,tom,observacoes,storage_path) on public.cifra_envios to authenticated;
grant update (status) on public.cifra_envios to authenticated;
grant usage on sequence public.cifra_envios_id_seq to authenticated;

-- Somente a cifra aprovada tem URL pública.
create table if not exists public.cifras_publicadas (
  hino_numero int primary key check (hino_numero between 1 and 9999),
  origem_envio bigint references public.cifra_envios(id) on delete set null,
  storage_path text not null check (storage_path ~ '^hino-[0-9]+-[0-9]+\.pdf$'),
  publicado_em timestamptz not null default now()
);
alter table public.cifras_publicadas enable row level security;
drop policy if exists "Leitura de cifra aprovada" on public.cifras_publicadas;
create policy "Leitura de cifra aprovada" on public.cifras_publicadas
  for select to anon,authenticated using (true);
drop policy if exists "Administrador publica cifra" on public.cifras_publicadas;
create policy "Administrador publica cifra" on public.cifras_publicadas
  for insert to authenticated with check ((select public.is_site_admin()));
drop policy if exists "Administrador substitui cifra" on public.cifras_publicadas;
create policy "Administrador substitui cifra" on public.cifras_publicadas
  for update to authenticated using ((select public.is_site_admin()))
  with check ((select public.is_site_admin()));
revoke all on public.cifras_publicadas from anon,authenticated;
grant select on public.cifras_publicadas to anon,authenticated;
grant insert (hino_numero,origem_envio,storage_path) on public.cifras_publicadas to authenticated;
grant update (origem_envio,storage_path) on public.cifras_publicadas to authenticated;

-- Storage: 1 bucket privado para envios + 1 público APENAS para PDF aprovado.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('cifras-envios','cifras-envios',false,5242880,array['application/pdf'])
on conflict (id) do update set public=false,file_size_limit=5242880,allowed_mime_types=array['application/pdf'];
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('cifras-publicadas','cifras-publicadas',true,5242880,array['application/pdf'])
on conflict (id) do update set public=true,file_size_limit=5242880,allowed_mime_types=array['application/pdf'];

drop policy if exists "PDF privado upload colaborador" on storage.objects;
create policy "PDF privado upload colaborador" on storage.objects
  for insert to authenticated
  with check (
    bucket_id='cifras-envios'
    and (storage.foldername(name))[1]=(select auth.uid())::text
    and storage.extension(name)='pdf'
  );
drop policy if exists "PDF privado ler somente dono ou admin" on storage.objects;
create policy "PDF privado ler somente dono ou admin" on storage.objects
  for select to authenticated
  using (
    bucket_id='cifras-envios' and
    ((storage.foldername(name))[1]=(select auth.uid())::text or (select public.is_site_admin()))
  );
drop policy if exists "PDF privado excluir pelo dono" on storage.objects;
create policy "PDF privado excluir pelo dono" on storage.objects
  for delete to authenticated
  using (bucket_id='cifras-envios' and (storage.foldername(name))[1]=(select auth.uid())::text);

drop policy if exists "Publicar PDF apenas admin" on storage.objects;
create policy "Publicar PDF apenas admin" on storage.objects
  for insert to authenticated
  with check (
    bucket_id='cifras-publicadas' and (select public.is_site_admin())
    and storage.extension(name)='pdf'
  );
drop policy if exists "Admin gerencia PDF publicado" on storage.objects;
create policy "Admin gerencia PDF publicado" on storage.objects
  for delete to authenticated
  using (bucket_id='cifras-publicadas' and (select public.is_site_admin()));

