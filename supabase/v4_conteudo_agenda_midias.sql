create table if not exists public.hinos_edicoes (
  numero integer primary key check(numero between 1 and 9999),
  titulo text not null check(char_length(btrim(titulo)) between 2 and 140),
  letra text not null check(char_length(btrim(letra)) between 3 and 20000),
  cifra text check(cifra is null or char_length(cifra)<=20000),
  tom text check(tom is null or char_length(tom)<=20),
  autor text check(autor is null or char_length(autor)<=120),
  atualizado_em timestamptz not null default now()
);
alter table public.hinos_edicoes enable row level security;
drop policy if exists "v4 hinos leitura" on public.hinos_edicoes;
create policy "v4 hinos leitura" on public.hinos_edicoes for select to anon,authenticated using(true);
drop policy if exists "v4 hinos insert admin" on public.hinos_edicoes;
create policy "v4 hinos insert admin" on public.hinos_edicoes for insert to authenticated with check ((select public.is_site_admin()));
drop policy if exists "v4 hinos update admin" on public.hinos_edicoes;
create policy "v4 hinos update admin" on public.hinos_edicoes for update to authenticated using ((select public.is_site_admin())) with check ((select public.is_site_admin()));
revoke all on public.hinos_edicoes from anon,authenticated;
grant select on public.hinos_edicoes to anon,authenticated;
grant insert (numero,titulo,letra,cifra,tom,autor) on public.hinos_edicoes to authenticated;
grant update (titulo,letra,cifra,tom,autor) on public.hinos_edicoes to authenticated;

