create or replace function public.v4_auditar_moderacao()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if new.status is distinct from old.status then
    insert into public.site_moderacao_historico(tipo,referencia_id,acao,administrador_id)
    values(TG_ARGV[0],new.id,new.status,(select auth.uid()));
  end if;
  return new;
end;
$$;
revoke all on function public.v4_auditar_moderacao() from public,anon,authenticated;
drop trigger if exists v4_auditar_comentarios on public.comentarios;
create trigger v4_auditar_comentarios after update of status on public.comentarios
for each row execute function public.v4_auditar_moderacao('comentario');
drop trigger if exists v4_auditar_cifras on public.cifra_envios;
create trigger v4_auditar_cifras after update of status on public.cifra_envios
for each row execute function public.v4_auditar_moderacao('cifra');

