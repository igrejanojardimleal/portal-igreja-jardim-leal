-- Datas anuais: não coletar ano de nascimento; batismo e chamados aceitam ano opcional.
create table if not exists public.site_celebracoes(
 id bigint generated by default as identity primary key,
 nome text not null check(char_length(btrim(nome)) between 2 and 100),
 tipo text not null check(tipo in ('aniversario','batismo','diaconato','pastorado','casamento','ministerio')),
 dia smallint not null check(dia between 1 and 31),
 mes smallint not null check(mes between 1 and 12),
 ano_referencia smallint check(ano_referencia between 1900 and 2100),
 consentimento_confirmado boolean not null default false check(consentimento_confirmado),
 publicado boolean not null default false,
 criado_em timestamptz not null default now(),
 constraint aniversario_sem_ano check(tipo<>'aniversario' or ano_referencia is null),
 constraint data_valida check(dia <= extract(day from (make_date(2024,mes,1) + interval '1 month - 1 day')))
);
create index if not exists celebracoes_mes_dia on public.site_celebracoes(mes,dia) where publicado;
alter table public.site_celebracoes enable row level security;
create policy "v7 celebracoes leitura" on public.site_celebracoes for select to anon,authenticated
 using(publicado or (select public.can_manage_events()));
create policy "v7 celebracoes criar" on public.site_celebracoes for insert to authenticated
 with check ((select public.can_manage_events()));
create policy "v7 celebracoes atualizar" on public.site_celebracoes for update to authenticated
 using((select public.can_manage_events())) with check((select public.can_manage_events()));
create policy "v7 celebracoes apagar" on public.site_celebracoes for delete to authenticated
 using((select public.can_manage_events()));
revoke all on public.site_celebracoes from anon,authenticated;
grant select(id,nome,tipo,dia,mes,ano_referencia,publicado,criado_em) on public.site_celebracoes to anon,authenticated;
grant insert(nome,tipo,dia,mes,ano_referencia,publicado,consentimento_confirmado) on public.site_celebracoes to authenticated;
grant update(nome,tipo,dia,mes,ano_referencia,publicado,consentimento_confirmado) on public.site_celebracoes to authenticated;
grant delete on public.site_celebracoes to authenticated;
grant usage on sequence public.site_celebracoes_id_seq to authenticated;

