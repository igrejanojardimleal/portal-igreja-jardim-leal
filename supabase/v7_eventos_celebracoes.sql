create table if not exists public.site_event_managers(
 user_id uuid primary key references auth.users(id) on delete cascade,
 criado_em timestamptz not null default now()
);
alter table public.site_event_managers enable row level security;
revoke all on public.site_event_managers from anon,authenticated;

create or replace function public.can_manage_events()
returns boolean language sql stable security definer set search_path=''
as $$
 select (select auth.uid()) is not null and (
  (select public.is_site_admin()) or exists(
   select 1 from public.site_event_managers m where m.user_id=(select auth.uid())
  )
 );
$$;
revoke all on function public.can_manage_events() from public;
grant execute on function public.can_manage_events() to anon,authenticated;

-- As políticas antigas de admin geral são substituídas por acesso à equipe de eventos.
drop policy if exists "v4 eventos ler" on public.site_eventos;
drop policy if exists "v4 eventos criar" on public.site_eventos;
drop policy if exists "v4 eventos editar" on public.site_eventos;
drop policy if exists "v4 eventos excluir" on public.site_eventos;
create policy "v7 eventos leitura" on public.site_eventos for select to anon,authenticated
 using(publicado or (select public.can_manage_events()));
create policy "v7 eventos criar" on public.site_eventos for insert to authenticated
 with check ((select public.can_manage_events()));
create policy "v7 eventos editar" on public.site_eventos for update to authenticated
 using((select public.can_manage_events())) with check((select public.can_manage_events()));
create policy "v7 eventos apagar" on public.site_eventos for delete to authenticated
 using((select public.can_manage_events()));

